import { chromium } from 'playwright'
const b = await chromium.launch({ args: ['--enable-unsafe-webgpu','--enable-features=Vulkan','--use-vulkan=swiftshader','--enable-unsafe-swiftshader'] })
const ctx = await b.newContext({ viewport: { width: 1280, height: 800 }, deviceScaleFactor: 1 })
await ctx.addInitScript(() => { try { sessionStorage.setItem('cc-gate-override','1') } catch {} })
const p = await ctx.newPage()
await p.goto('http://localhost:3131/grid', { waitUntil: 'domcontentloaded' })
await p.waitForTimeout(3000)
const rect = () => p.evaluate(() => {
  const cv = document.querySelector('canvas'); const r = cv.getBoundingClientRect()
  return { w: Math.round(r.width), h: Math.round(r.height), top: Math.round(r.top) }
})
const r1 = await rect()
console.log('BROWSE (mini @top):', JSON.stringify(r1), r1.w < 700 && r1.top < 40 ? '✓' : '✗')
const tiles = await p.evaluate(() => [...document.querySelectorAll('button')].filter(b2 => /CINDERFELL|STARFIELD/.test(b2.textContent||'')).length)
console.log('shelf tiles:', tiles)
await p.click('button:has-text("STARFIELD")'); await p.waitForTimeout(2200)
console.log('picked STARFIELD · url w=', await p.evaluate(() => new URL(location.href).searchParams.get('w')))
console.log('step: click frame to play')
await p.click('[aria-label^="play"]', { timeout: 8000 }); await p.waitForTimeout(600)
const r2 = await rect()
console.log('PLAY:', JSON.stringify(r2), r2.w > r1.w ? '(expanded ✓)' : '✗', '· ph=', await p.evaluate(() => new URL(location.href).searchParams.get('ph')))
// back via THE DOCKSTAR (the one way): cup → GAMES
console.log('step: open dockstar')
await p.click('[aria-label="ui selector"]', { timeout: 8000 }); await p.waitForTimeout(300)
console.log('step: pick GAMES set')
await p.getByText('browse the shelf', { exact: false }).click({ timeout: 8000 }); await p.waitForTimeout(600)
const r3 = await rect()
console.log('DOCKSTAR→GAMES:', JSON.stringify(r3), r3.w < r2.w ? '(browse again ✓)' : '✗')
// instructions overlay never covers the bar
await p.locator('button', { hasText: '? INSTRUCTIONS' }).last().click({ timeout: 8000 }); await p.waitForTimeout(800)
const bar = await p.evaluate(() => {
  const cup = document.querySelector('[aria-label="ui selector"]')
  const r = cup.getBoundingClientRect()
  const el = document.elementFromPoint(r.x + r.width/2, r.y + r.height/2)
  return el === cup || cup.contains(el)
})
console.log('bar clickable under instructions overlay:', bar ? '✓' : '✗')
await b.close(); console.log('SHELF LOOP COMPLETE')
